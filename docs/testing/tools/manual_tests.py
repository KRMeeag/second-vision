#!/usr/bin/env python3
"""Regenerate the case list in MANUAL-TESTS.md: every UAT case that needs a person.

    python3 docs/testing/tools/manual_tests.py           # rewrite the generated section
    python3 docs/testing/tools/manual_tests.py --check   # exit 1 if it is out of date

A case is listed when its Test column in TRACEABILITY.md starts with `assisted`, `manual`
or `esp32-manual`. Steps, input and expected result are quoted from uat-snapshot.yaml;
requirements and tasks come from TRACEABILITY.md. Only the text between the BEGIN and END
markers is replaced; everything else in MANUAL-TESTS.md is written by hand.

Standard library plus PyYAML.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

TESTING = Path(__file__).resolve().parents[1]
TARGET = TESTING / "MANUAL-TESTS.md"
BEGIN = "<!-- BEGIN GENERATED by tools/manual_tests.py: do not edit by hand -->"
END = "<!-- END GENERATED -->"
WORKFLOW_TYPES = ("assisted", "manual")
ESP32_TYPE = "esp32-manual"


def _flat(text: str | None) -> str:
    return " ".join((text or "").split()) or "—"


def _matrix() -> dict[str, dict[str, str]]:
    trace = (TESTING / "TRACEABILITY.md").read_text()
    matrix = trace.split("## Matrix", 1)[1].split("## Requirements with no UAT case", 1)[0]
    rows: dict[str, dict[str, str]] = {}
    for line in matrix.splitlines():
        if not line.startswith("| TC-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        test_type = re.split(r"[\s(·]", cells[4], maxsplit=1)[0]
        rows[cells[0].split(" ")[0]] = {"req": cells[1], "task": cells[3], "type": test_type}
    return rows


def _case_block(cid: str, case: dict, row: dict[str, str]) -> list[str]:
    task = "" if row["task"] in ("—", "") else f" · {row['task']}"
    lines = [f"#### {cid} · {row['type']} · {row['req']}{task}", ""]
    lines.append(f"- **Steps:** {_flat(case.get('steps'))}")
    if case.get("input"):
        lines.append(f"- **Input:** {_flat(case.get('input'))}")
    lines.append(f"- **Expected (workbook):** {_flat(case.get('expected'))}")
    lines.append("")
    return lines


def render() -> str:
    """The generated section, markers included."""
    snap = yaml.safe_load((TESTING / "uat-snapshot.yaml").read_text())
    rows = _matrix()
    picked = {cid: row for cid, row in rows.items()
              if row["type"] in WORKFLOW_TYPES + (ESP32_TYPE,)}
    out = [BEGIN, ""]
    parts = (
        ("In the agent workflow (`assisted`: a person sets up the scene or plugs hardware; "
         "`manual`: a person judges by ear or feel)", WORKFLOW_TYPES),
        ("ESP32 cases: run by the team by hand, outside the agent workflow", (ESP32_TYPE,)),
    )
    for title, types in parts:
        cases = [cid for cid in sorted(picked) if picked[cid]["type"] in types]
        out += [f"### {title}: {len(cases)} cases", ""]
        module = scenario = None
        for cid in cases:
            case = snap["cases"][cid]
            if case["module"] != module:
                module = case["module"]
                out += [f"**{module} · {snap['modules'][module]['name']}**", ""]
            if case["scenario"] != scenario:
                scenario = case["scenario"]
                out += [f"*{scenario} · {case['scenario_title']}*", ""]
            out += _case_block(cid, case, picked[cid])
    out.append(END)
    return "\n".join(out)


def current() -> str:
    """The generated section as it is in MANUAL-TESTS.md now ("" if missing)."""
    text = TARGET.read_text() if TARGET.exists() else ""
    if BEGIN not in text or END not in text:
        return ""
    return BEGIN + text.split(BEGIN, 1)[1].split(END, 1)[0] + END


def main() -> int:
    """Entry point; returns the process exit code."""
    fresh = render()
    if "--check" in sys.argv:
        if current() != fresh:
            print("MANUAL-TESTS.md case list is out of date: run tools/manual_tests.py")
            return 1
        print("MANUAL-TESTS.md case list is current")
        return 0
    text = TARGET.read_text()
    if BEGIN not in text or END not in text:
        print(f"markers missing in {TARGET}", file=sys.stderr)
        return 1
    before = text.split(BEGIN, 1)[0]
    after = text.split(END, 1)[1]
    TARGET.write_text(before + fresh + after)
    print(f"wrote {TARGET.name}: {fresh.count('#### TC-')} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
